#Entrada
"""
Recibiras un numero entero
"""
#Salida
"""
Deberás mostrar "Positivo" en caso de que el número sea Positivo.
Deberás mostrar "Negativo" en caso de que el número sea Negativo. 
"""

Numero = int(input())
if Numero >= 0:
    print("Positivo")
else: print("Negativo")